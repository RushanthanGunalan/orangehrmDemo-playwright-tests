/**
 * Writes docs/OrangeHRM-Test-Suite.xlsx from the committed test-case list
 * (docs/test-suite/test-cases.json). The spreadsheet is a generated export:
 * edit the JSON (or let `pnpm docs:sync` edit it), never the .xlsx.
 */

import ExcelJS from "exceljs";

export const SHEET = "OrangeHRM Test Suite";
const LAST_ROW = 200; // summary formulas cover rows 2..200 so appended cases are counted

const COLUMNS = [
  ["id", "Test Case ID", 16],
  ["priority", "Priority", 10],
  ["type", "Test Type", 12],
  ["module", "Module / Feature", 30],
  ["scenario", "Test Scenario", 42],
  ["steps", "Test Steps", 55],
  ["input", "Input Data", 42],
  ["expected", "Expected Result", 58],
  ["automated", "Automated", 12],
  ["spec", "Spec File", 34],
  ["notes", "Automation Notes", 50],
];

const TYPES = ["Smoke", "Functional", "Negative", "Navigation", "Unit"];
const TYPE_FILL = {
  Smoke: "FFD9EAD3",
  Functional: "FFCFE2F3",
  Negative: "FFF4CCCC",
  Navigation: "FFFFF2CC",
  Unit: "FFE4DFEC",
};

const solid = (argb) => ({ type: "pattern", pattern: "solid", fgColor: { argb }, bgColor: { argb } });
const thin = { style: "thin", color: { argb: "FFB7B7B7" } };
const BORDER = { left: thin, right: thin, top: thin, bottom: thin };
const CENTER = { horizontal: "center", vertical: "middle", wrapText: true };
const LEFT_WRAP = { horizontal: "left", vertical: "top", wrapText: true };

export async function writeTestSuiteWorkbook(rows, outPath) {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet(SHEET, { views: [{ state: "frozen", xSplit: 1, ySplit: 1 }] });

  ws.columns = COLUMNS.map(([key, header, width]) => ({ key, header, width }));
  ws.getRow(1).height = 24;
  ws.getRow(1).eachCell((cell) => {
    cell.font = { name: "Arial", bold: true, color: { argb: "FFFFFFFF" }, size: 11 };
    cell.fill = solid("FF1F4E78");
    cell.alignment = CENTER;
    cell.border = BORDER;
  });

  rows.forEach((row) => {
    const r = ws.addRow(COLUMNS.map(([key]) => row[key] ?? ""));
    r.height = 78;
    r.eachCell({ includeEmpty: true }, (cell, col) => {
      cell.font = { name: "Arial", size: 10 };
      cell.border = BORDER;
      cell.alignment = [1, 2, 3, 9].includes(col) ? CENTER : LEFT_WRAP;
    });
    const fill = TYPE_FILL[row.type];
    if (fill) r.getCell(3).fill = solid(fill);
  });

  // Automated column: colour follows the VALUE, so flipping Planned -> Yes recolours it.
  const rule = (value, argb) => ({
    type: "expression",
    formulae: [`$I2="${value}"`],
    style: { fill: { type: "pattern", pattern: "solid", bgColor: { argb } } },
  });
  ws.addConditionalFormatting({
    ref: `I2:I${LAST_ROW}`,
    rules: [rule("Yes", "FFC6EFCE"), rule("Planned", "FFFFEB9C")],
  });
  for (let r = 2; r <= LAST_ROW; r++) {
    ws.getCell(`I${r}`).dataValidation = { type: "list", allowBlank: true, formulae: ['"Yes,Planned,No"'] };
  }
  ws.autoFilter = `A1:K${Math.max(rows.length + 1, 2)}`;

  // Summary: formulas over the main sheet, so it updates when the sheet is edited.
  const sm = wb.addWorksheet("Summary");
  const q = `'${SHEET}'`;
  const rng = (col) => `${q}!$${col}$2:$${col}$${LAST_ROW}`;
  const types = [...new Set([...TYPES, ...rows.map((r) => r.type).filter(Boolean)])];
  const first = 8;
  const last = first + types.length - 1;
  const totalRow = last + 1;

  sm.getCell("A1").value = "OrangeHRM Playwright Test Suite - Summary";
  sm.getCell("A1").font = { name: "Arial", bold: true, size: 14 };
  sm.getCell("A3").value = "Total test cases";
  sm.getCell("B3").value = { formula: `COUNTA(${rng("A")})` };
  sm.getCell("A4").value = "Automated";
  sm.getCell("B4").value = { formula: `COUNTIF(${rng("I")},"Yes")` };
  sm.getCell("A5").value = "Planned (not automated yet)";
  sm.getCell("B5").value = { formula: `COUNTIF(${rng("I")},"Planned")` };
  ["Type", "Total", "Automated", "Planned"].forEach((h, i) => (sm.getCell(7, i + 1).value = h));
  types.forEach((t, i) => {
    const r = first + i;
    sm.getCell(`A${r}`).value = t;
    sm.getCell(`B${r}`).value = { formula: `COUNTIF(${rng("C")},A${r})` };
    sm.getCell(`C${r}`).value = { formula: `COUNTIFS(${rng("C")},A${r},${rng("I")},"Yes")` };
    sm.getCell(`D${r}`).value = { formula: `COUNTIFS(${rng("C")},A${r},${rng("I")},"Planned")` };
  });
  sm.getCell(`A${totalRow}`).value = "All types";
  for (const col of "BCD") sm.getCell(`${col}${totalRow}`).value = { formula: `SUM(${col}${first}:${col}${last})` };

  const noteRow = totalRow + 2;
  sm.getCell(`A${noteRow}`).value =
    "Generated by `pnpm docs:sync` from docs/test-suite/test-cases.json - edit that file, not this sheet. " +
    "Planned cases' types are provisional until each is automated. 'All types' should equal Total test " +
    "cases above; if not, a case has a Type outside the listed ones.";
  sm.mergeCells(`A${noteRow}:D${noteRow}`);
  sm.getRow(noteRow).height = 60;
  sm.getCell(`A${noteRow}`).alignment = { wrapText: true, vertical: "top" };
  sm.getCell(`A${noteRow}`).font = { name: "Arial", size: 9, italic: true };

  for (let r = 3; r <= totalRow; r++) {
    for (let c = 1; c <= 4; c++) sm.getCell(r, c).font = { name: "Arial", size: 11 };
  }
  for (const ref of ["A7", "B7", "C7", "D7", `A${totalRow}`, `B${totalRow}`, `C${totalRow}`, `D${totalRow}`]) {
    sm.getCell(ref).font = { name: "Arial", size: 11, bold: true };
  }
  sm.getColumn("A").width = 30;
  for (const col of "BCD") sm.getColumn(col).width = 12;

  wb.calcProperties.fullCalcOnLoad = true;
  await wb.xlsx.writeFile(outPath);
}
